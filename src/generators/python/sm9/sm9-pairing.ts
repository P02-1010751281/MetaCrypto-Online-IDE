    '    ret = sm9_mul_line_b6(ret, a, b, c)',
    '    # final exponentiation: f^{(p^12-1)/r}',
    '    return ret.pow((SM9P ** 12 - 1) // SM9N)',
    '',
    '# ---------- SM9 signature scheme ----------',
    'def sm9_keygen(ks: int, uid: bytes, hid: int):',
    '    """Returns (ds: G1, Ppub: G2, g: F12)."""',
    '    t1 = sm9_H1(uid + bytes([hid]))',
    '    t1 = (t1 + ks) % SM9N',
    '    if t1 == 0:',
    '        raise ValueError(\'bad master key\')',
    '    t2 = ks * pow(t1, SM9N - 2, SM9N) % SM9N',
    '    ds = SM9_P1_G.mul(t2)',
    '    ppub = SM9_P2_G.mul(ks)',
    '    g = sm9_pairing(ppub, SM9_P1_G)  # e(P1, Ppub)',
