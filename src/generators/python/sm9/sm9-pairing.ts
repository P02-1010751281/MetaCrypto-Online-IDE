    '    if len(ks_bytes) != 32:',
    '        raise ValueError(\'SM9 master key must be 32 bytes\')',
    '    k = int.from_bytes(ks_bytes, \'big\')',
    '    if not 1 <= k < SM9N:',
    '        raise ValueError(\'SM9 master key must satisfy 1 <= ks < n\')',
    '    return k',
    '',
    'def sm9_master_key(ks):',
    '    k = sm9_master_scalar(ks)',
    '    ppub = SM9_P2_G.mul(k)',
