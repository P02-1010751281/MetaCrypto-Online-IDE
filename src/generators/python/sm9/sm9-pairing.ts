    '',
    'def sm9_user_key(ks, uid, hid):',
    '    k = sm9_master_scalar(ks)',
    '    uid = sm9_require_bytes(uid, \'ID\')',
    '    if type(hid) is not int or hid != 1:',
    '        raise ValueError(\'SM9 signing key requires HID 0x01\')',
    '    ds, ppub, g = sm9_keygen(k, bytes(uid), hid)',
