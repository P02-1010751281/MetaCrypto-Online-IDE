    'def sm9_g2_parse_raw(b):',
    '    c = [int.from_bytes(bytes(b[k*32:(k+1)*32]), \'big\') for k in range(4)]',
    '    return SM9_G2(SM9_F2(c[0], c[1]), SM9_F2(c[2], c[3]), SM9_F2.one(), SM9_F2.one())',
    '',
    '# ---------- block entry points (BYTES in/out, list of ints) ----------',
