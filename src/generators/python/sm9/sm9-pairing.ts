    '    b_aff = SM9_G1(p.x, p.y, p.z); b_aff = b_aff.affine()   # (x, y) tuple',
    '    r = SM9_G2(a_aff.x, a_aff.y, a_aff.z, a_aff.t)',
    '    r2 = a_aff.y.sqr()',
    '    new_r = SM9_G2()',
    '    for i in range(len(SM9_NAF_6U2) - 1, 0, -1):',
    '        a = b = c = None',
    '        a, b, c = sm9_line_function_double(r, new_r, b_aff)',
    '        if i != len(SM9_NAF_6U2) - 1:',
    '            ret = ret.sqr()',
    '        ret = sm9_mul_line_b6(ret, a, b, c)',
    '        r, new_r = new_r, r',
    '        d = SM9_NAF_6U2[i - 1]',
    '        if d == 1:',
    '            a, b, c = sm9_line_function_add(r, a_aff, new_r, b_aff, r2)',
    '        elif d == -1:',
    '            a, b, c = sm9_line_function_add(r, minus_a, new_r, b_aff, r2)',
    '        else:',
    '            continue',
    '        ret = sm9_mul_line_b6(ret, a, b, c)',
    '        r, new_r = new_r, r',
    '    # Q1 = [p]Q, minusQ2 = -[p²]Q',
    '    q1 = SM9_G2()',
    '    q1.x = a_aff.x.conj().mul_scalar(SM9_BETA_NEG_PP1_O3)',
    '    q1.y = a_aff.y.conj().mul_scalar(SM9_BETA_NEG_PP1_O2)',
    '    q1.z = SM9_F2.one(); q1.t = SM9_F2.one()',
    '    mq2 = SM9_G2()',
    '    mq2.x = a_aff.x.mul_scalar(SM9_BETA_NEG_P2P1_O3)',
    '    mq2.y = (-a_aff.y).mul_scalar(SM9_BETA_NEG_P2P1_O2)',
    '    mq2.z = SM9_F2.one(); mq2.t = SM9_F2.one()',
    '    r2 = q1.y.sqr()',
    '    a, b, c = sm9_line_function_add(r, q1, new_r, b_aff, r2)',
    '    ret = sm9_mul_line_b6(ret, a, b, c)',
