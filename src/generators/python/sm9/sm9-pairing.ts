    '',
    'def sm9_sign_impl(msg: bytes, ds: SM9_G1, ppub: SM9_G2, r: int):',
    '    g = sm9_pairing(ppub, SM9_P1_G)',
    '    w = g.pow(r)',
    '    h = sm9_H2(msg + sm9_gt_marshal(w))',
    '    l = (r - h) % SM9N',
    '    if l == 0:',
    '        return None',
    '    S = ds.mul(l)',
    '    return h, S',
    '',
    'def sm9_verify_impl(msg: bytes, uid: bytes, hid: int, ppub: SM9_G2, h: int, S: SM9_G1) -> bool:',
    '    if h <= 0 or h >= SM9N:',
    '        return False',
    '    if not S.is_on_curve() or S.is_inf():',
    '        return False',
    '    if not sm9_g1_mul_raw(S, SM9N).is_inf():',
    '        return False',
    '    t1 = sm9_H1(uid + bytes([hid]))',
    '    Q = SM9_P2_G.mul(t1).add(ppub)',
    '    g = sm9_pairing(ppub, SM9_P1_G)',
    '    u = sm9_pairing(Q, S)          # e(S, Q)',
    '    w = u.mul(g.pow(h))',
    '    h2 = sm9_H2(msg + sm9_gt_marshal(w))',
    '    return h2 == h',
    '',
