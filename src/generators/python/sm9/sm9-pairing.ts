    '# ---------- pairing ----------',
    'def sm9_pairing(q: SM9_G2, p: SM9_G1) -> SM9_F12:',
    '    """e(P, Q) = R-ate pairing, computed as miller(Q, P) with Q ∈ G2, P ∈ G1."""',
    '    ret = SM9_F12.one()',
    '    a_aff = SM9_G2(q.x, q.y, q.z, q.t); a_aff.make_affine()',
